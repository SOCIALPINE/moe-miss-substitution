"""Exercise prep_data.py end-to-end with fake local files that mimic the real schemas."""
import os, sys, json, gzip, random, subprocess, shutil
import numpy as np
import pyarrow as pa, pyarrow.parquet as pq
from tokenizers import Tokenizer, models, pre_tokenizers, decoders, trainers
from transformers import PreTrainedTokenizerFast

B = "/tmp/moe_test/fakeprep"
shutil.rmtree(B, ignore_errors=True)
os.makedirs(B)
random.seed(0)
words = "alpha beta gamma delta 한국어 문장 테스트 def return import class print for while 수학 문제 풀이".split()


def para(n):
    return " ".join(random.choice(words) for _ in range(n))


# tokenizer
tk = Tokenizer(models.BPE())
tk.pre_tokenizer = pre_tokenizers.ByteLevel(add_prefix_space=False)
tk.decoder = decoders.ByteLevel()
tk.train_from_iterator([para(200) for _ in range(200)], trainers.BpeTrainer(vocab_size=400, special_tokens=["<|im_start|>", "<|im_end|>"]))
t = PreTrainedTokenizerFast(tokenizer_object=tk)
t.chat_template = "{% for m in messages %}<|im_start|>{{ m['role'] }}\n{{ m['content'] }}<|im_end|>\n{% endfor %}"
md = B + "/model"
t.save_pretrained(md)


def pqw(repo, fn, table):
    p = os.path.join(B, "data", repo.replace("/", "__"), fn)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    pq.write_table(table, p)


N = 300
pqw("wikimedia/wikipedia", "20231101.ko/train-00001-of-00003.parquet",
    pa.table({"id": [str(i) for i in range(N)], "title": ["t"] * N, "text": [para(random.choice([100, 900, 2500])) for _ in range(N)]}))
for i in range(5):
    pqw("wikimedia/wikipedia", f"20231101.en/train-0000{i}-of-00041.parquet",
        pa.table({"title": ["t"] * N, "text": [para(random.choice([100, 3000])) for _ in range(N)]}))
pqw("HuggingFaceH4/ultrachat_200k", "data/test_sft-00000-of-00001-f7dfac4afe5b93f4.parquet",
    pa.table({"messages": [[{"content": para(random.choice([300, 800])), "role": r} for r in ("user", "assistant")] for _ in range(N)]}))
pqw("maywell/koVast", "data/train-00001-of-00003-76f1a8992c6a4ebe.parquet",
    pa.table({"conversations": [[{"from": f, "value": para(random.choice([100, 900]))} for f in ("human", "gpt", "human", "gpt")] for _ in range(N)]}))
pqw("AI-MO/NuminaMath-CoT", "data/train-00000-of-00005.parquet",
    pa.table({"source": ["x"] * N, "problem": [para(50) for _ in range(N)], "solution": [para(150) for _ in range(N)]}))
p = os.path.join(B, "data", "codeparrot__codeparrot-clean-valid", "file-000000000054.json.gz")
os.makedirs(os.path.dirname(p), exist_ok=True)
with gzip.open(p, "wt") as f:
    for _ in range(N):
        f.write(json.dumps({"content": para(random.choice([200, 3000])), "autogenerated": False}) + "\n")

env = dict(os.environ, PREP_FAKE_DIR=B + "/data")
r = subprocess.run([sys.executable, "prep_data.py", "--model_dir", md, "--out", B + "/out", "--seq_len", "512",
                    "--per_domain", "8", "--prompt_len", "128"], env=env, capture_output=True, text=True)
print(r.stdout[-5000:], r.stderr[-3000:])
assert r.returncode == 0
d = np.load(B + "/out/sessions.npz")
print(d["tokens"].shape, np.bincount(d["domain"]), d["domain_names"], int(d["prompt_len"]))
assert d["tokens"].shape == (48, 512)
print("PREP TEST PASSED")
